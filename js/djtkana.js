var daily = {};
var last_review_time = null;

function pad2(n) {
	return (n < 10 ? '0' : '') + n;
}

function date_key(d) {
	return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
}

function load_daily() {
	try {
		var raw = localStorage.getItem('kana_daily');
		daily = raw ? JSON.parse(raw) : {};
	} catch (e) {
		daily = {};
	}
}

function save_daily() {
	localStorage.setItem('kana_daily', JSON.stringify(daily));
}

function record_daily_review() {
	var key = date_key(new Date());
	if (!daily[key]) {
		daily[key] = { count: 0, ms: 0 };
	}
	daily[key].count += 1;

	var now = Date.now();
	if (last_review_time && (now - last_review_time) < 60000) {
		daily[key].ms += (now - last_review_time);
	}
	last_review_time = now;

	save_daily();
	render_streak_panel();
}

function render_streak_panel() {
	var panel = document.getElementById('streakPanel');
	if (!panel) {
		return;
	}

	var today = new Date();
	today.setHours(0, 0, 0, 0);
	var today_str = date_key(today);
	var today_data = daily[today_str] || { count: 0, ms: 0 };

	var header;
	if (today_data.count == 0) {
		header = 'No reviews yet today.';
	} else if (today_data.ms > 0) {
		var minutes = today_data.ms / 60000;
		var spc = (today_data.ms / 1000) / today_data.count;
		header = 'Studied ' + today_data.count + ' card' + (today_data.count == 1 ? '' : 's') + ' in ' + minutes.toFixed(2) + ' minutes today (' + spc.toFixed(2) + 's/card)';
	} else {
		header = 'Studied ' + today_data.count + ' card' + (today_data.count == 1 ? '' : 's') + ' today';
	}

	var window_days = 91;
	var start = new Date(today);
	start.setDate(start.getDate() - (window_days - 1));
	start.setDate(start.getDate() - start.getDay());

	var cells = [];
	var max_count = 1;
	var cursor = new Date(start);
	while (cursor <= today) {
		var key = date_key(cursor);
		var count = (daily[key] && daily[key].count) || 0;
		if (count > max_count) {
			max_count = count;
		}
		cells.push({ key: key, count: count, is_today: key == today_str });
		cursor.setDate(cursor.getDate() + 1);
	}

	var grid_html = '';
	for (var i = 0; i < cells.length; i++) {
		var c = cells[i];
		var level = 0;
		if (c.count > 0) {
			var ratio = c.count / max_count;
			level = ratio > 0.75 ? 4 : (ratio > 0.5 ? 3 : (ratio > 0.25 ? 2 : 1));
		}
		grid_html += '<div class="heat-cell heat-' + level + (c.is_today ? ' heat-today' : '') + '" title="' + c.key + ': ' + c.count + ' review' + (c.count == 1 ? '' : 's') + '"></div>';
	}

	var active_days = {};
	for (var k in daily) {
		if (daily[k].count > 0) {
			active_days[k] = true;
		}
	}

	var current_streak = 0;
	var walk = new Date(today);
	while (active_days[date_key(walk)]) {
		current_streak += 1;
		walk.setDate(walk.getDate() - 1);
	}

	var sorted_active = Object.keys(active_days).sort();
	var longest_streak = 0;
	var run = 0;
	var prev_date = null;
	for (i = 0; i < sorted_active.length; i++) {
		var dt = new Date(sorted_active[i] + 'T00:00:00');
		if (prev_date && Math.round((dt - prev_date) / 86400000) == 1) {
			run += 1;
		} else {
			run = 1;
		}
		if (run > longest_streak) {
			longest_streak = run;
		}
		prev_date = dt;
	}

	var active_in_window = 0;
	var total_in_window = 0;
	for (i = 0; i < cells.length; i++) {
		if (cells[i].count > 0) {
			active_in_window += 1;
		}
		total_in_window += cells[i].count;
	}
	var days_active_pct = Math.round((active_in_window / cells.length) * 100);
	var daily_average = Math.round(total_in_window / cells.length);

	panel.innerHTML =
		'<div class="streak-header">' + header + '</div>' +
		'<div class="heatmap">' + grid_html + '</div>' +
		'<div class="streak-summary">' +
			'<span><span class="streak-value">' + daily_average + '</span> avg cards/day</span>' +
			'<span><span class="streak-value">' + days_active_pct + '%</span> days active</span>' +
			'<span><span class="streak-value">' + longest_streak + '</span> longest streak</span>' +
			'<span><span class="streak-value">' + current_streak + '</span> current streak</span>' +
		'</div>';
}

function record_seen(k) {
	if (!stats[k]) {
		stats[k] = { seen: 0, wrong: 0, level: 0 };
	}
	stats[k].seen += 1;
	save_stats();
}

function record_mistake(k) {
	if (!stats[k]) {
		stats[k] = { seen: 0, wrong: 0, level: 0 };
	}
	stats[k].wrong += 1;
	save_stats();
}

var level_weights = [10, 6, 4, 2, 1, 1];
var level_labels = ['new', 'learning', 'learning', 'practicing', 'practicing', 'mastered'];
var max_level = level_weights.length - 1;

function update_level(k, correct) {
	if (!stats[k]) {
		stats[k] = { seen: 0, wrong: 0, level: 0 };
	}
	if (typeof stats[k].level != 'number') {
		stats[k].level = 0;
	}
	if (correct) {
		stats[k].level = Math.min(stats[k].level + 1, max_level);
	} else {
		stats[k].level = Math.max(stats[k].level - 2, 0);
	}
	save_stats();
}

function get_weight(k) {
	var level = (stats[k] && typeof stats[k].level == 'number') ? stats[k].level : 0;
	if (level < 0) {
		level = 0;
	}
	if (level >= level_weights.length) {
		level = level_weights.length - 1;
	}
	return level_weights[level];
}

function build_queue(items) {
	// Every checked kana gets at least level_weights[max] (>= 1) copies in
	// the pool, so a full pass through it always includes everything you've
	// checked - mastered kana just show up far less often, never absent.
	var pool = [];
	for (var i = 0; i < items.length; i++) {
		var w = get_weight(items[i][0]);
		for (var x = 0; x < w; x++) {
			pool.push(items[i]);
		}
	}
	return shuffle(pool);
}

function render_stats() {
	var body = document.getElementById('statsBody');
	var keys = Object.keys(stats).filter(function(k) { return stats[k].seen > 0; });

	if (keys.length == 0) {
		body.innerHTML = '<p class="stats-empty">No stats yet. Keep practicing!</p>';
		return;
	}

	keys.sort(function(a, b) {
		var la = (stats[a].level || 0);
		var lb = (stats[b].level || 0);
		if (la != lb) {
			return la - lb;
		}
		if (stats[b].wrong != stats[a].wrong) {
			return stats[b].wrong - stats[a].wrong;
		}
		return stats[b].seen - stats[a].seen;
	});

	var html = '<p class="stats-hint">Kana you struggle with show up more often; mastered kana show up less, but never disappear entirely.</p>';
	html += '<div class="stats-table-wrap"><table class="stats-table"><tr><th>Kana</th><th>Mistakes</th><th>Seen</th><th>Accuracy</th><th>Level</th></tr>';
	for (var i = 0; i < keys.length; i++) {
		var k = keys[i];
		var s = stats[k];
		var acc = Math.round((1 - s.wrong / s.seen) * 100);
		var level = s.level || 0;
		html += '<tr' + (s.wrong > 0 ? ' class="stats-row-miss"' : '') + '><td class="stats-kana">' + k + '</td><td>' + s.wrong + '</td><td>' + s.seen + '</td><td>' + acc + '%</td><td>' + level_labels[level] + '</td></tr>';
	}
	html += '</table></div>';
	body.innerHTML = html;
}

